-- 0043: свободная выплата зарплаты — «кому · сколько · когда».
-- Накатывается вручную через Supabase SQL Editor (как 0001–0042).
--
-- Правка от 13.08.2026 (решение David): вкладка «Расчёт выплат» становится
-- «Выплатой зарплаты», и деньги отмечаются не кнопкой у строки расчёта, а
-- формой: выбрал работника, вписал сумму, поставил дату, нажал «Выплачено».
--
-- ── Зачем ────────────────────────────────────────────────────────────────────
-- Отметка 0036 была жёстко привязана к периоду: строка = «за 3—9 августа
-- выдано столько-то», и одни и те же дни нельзя было закрыть дважды. Живая
-- касса так не работает: аванс отдают в среду, остаток в понедельник, часть
-- деньгами, часть переводом. Ни один из этих платежей не ложится в «период», а
-- заставлять начальника подгонять даты периода под факт выдачи — это ровно тот
-- ручной труд, ради отмены которого вкладка и делалась.
--
-- Поэтому период становится НЕОБЯЗАТЕЛЬНЫМ (у старых отметок он остаётся — это
-- их история, и переписывать её мы не имеем права); обязательным становится
-- день выдачи. У агентов такая таблица уже есть с 0023 (agent_payouts: сумма,
-- дата, комментарий), и теперь выплаты штату устроены так же — одна форма на
-- вкладке умеет и то, и другое.

-- ── Период больше не обязателен ──────────────────────────────────────────────
-- Уникальность (instructor_id, period_from, period_to) оставляем: она защищает
-- СТАРЫЕ отметки за период от дубля. Свободные выплаты идут с NULL-периодом, а
-- в Postgres NULL-и в уникальном индексе считаются различными — несколько
-- выплат одному человеку она не запрещает, что нам и нужно.
alter table salary_payouts alter column period_from drop not null;
alter table salary_payouts alter column period_to   drop not null;

-- ── День выдачи ──────────────────────────────────────────────────────────────
-- Именно по нему теперь считается «сколько я отдал за этот период» и строится
-- история выплат. У старых строк берём день отметки по вьетнамскому времени:
-- отмечали в момент выдачи, так что это та же дата.
alter table salary_payouts add column if not exists paid_on date;

update salary_payouts
   set paid_on = (paid_at at time zone 'Asia/Ho_Chi_Minh')::date
 where paid_on is null;

alter table salary_payouts alter column paid_on set not null;

comment on column salary_payouts.paid_on is 'День, когда деньги реально отдали. По нему считается «выплачено за период».';

-- ── Комментарий ──────────────────────────────────────────────────────────────
-- «аванс», «за прошлую неделю», «остаток» — то же поле, что у выплат агентам.
alter table salary_payouts add column if not exists comment text;

-- ── Связь с расходом школы ───────────────────────────────────────────────────
-- Выплата СММщику — единственная, которая создаёт расход: его фикс нигде в
-- финмодели не начисляется (в отличие от ЗП инструкторов, которая списывается
-- в момент записи занятия). Раньше этот расход искался обратно по тексту
-- подписи, и достаточно было переименовать человека, чтобы связь порвалась.
-- Теперь связь прямая. on delete set null: расход можно удалить руками во
-- вкладке «Расходы», выплата при этом остаётся — она про другое.
alter table salary_payouts add column if not exists expense_id uuid
  references expenses(id) on delete set null;

comment on column salary_payouts.expense_id is 'Расход школы, заведённый этой выплатой (только ЗП СММщика).';

create index if not exists salary_payouts_paid_on_idx on salary_payouts (paid_on);
