-- 0028: новая роль — механик.
-- Накатывается вручную через Supabase SQL Editor (как 0001–0027).
--
-- Механик следит за оборудованием и работает на пляже вместе с инструкторами:
-- смотрит календарь, заводит заявки, открывает свою смену с фотофиксацией,
-- вносит свои расходы. Зарплату по инструкторской схеме он НЕ получает —
-- поэтому в расчёты ЗП (lib/salary, lib/payroll, lib/stats) он не попадает:
-- там фильтр по role = 'instructor'.
--
-- ВАЖНО: этот файл накатывается ОТДЕЛЬНО и ПЕРВЫМ. Postgres не разрешает
-- использовать только что добавленное значение enum в той же транзакции
-- («unsafe use of new value of enum type»), а SQL Editor выполняет весь скрипт
-- одной транзакцией. Политики, где встречается 'mechanic', живут в 0029.

alter type user_role add value if not exists 'mechanic';
