-- 0030: инструктор больше не пишет напрямую в заявки, абонементы и награды.
-- Накатывается вручную через Supabase SQL Editor (как 0001–0029).
--
-- Та же причина, что в 0020 (смены): RLS проверяет СТРОКУ, но не умеет
-- ограничивать НАБОР КОЛОНОК. Политика вида «роль = instructor» разрешает
-- обновить в разрешённой строке что угодно — а у инструктора есть валидный
-- JWT, и запрос к PostgREST он может отправить мимо интерфейса.
--
-- Что было можно (проверено ревизией 2026-07-25):
--   • subscriptions_update_instructor — обновить ЛЮБОЙ абонемент целиком:
--     проставить себе sold_by, отметить paid_at (это выручка месяца и комиссия
--     продавца), накинуть total_minutes, переписать price;
--   • rewards_insert_instructor — выписать любому агенту награду любого
--     размера и сразу со статусом confirmed (то есть прямо в расчёт месяца);
--   • bookings_update_staff — переписать любую колонку любой заявки: статус,
--     телефон клиента, способ оплаты, «кто принял»;
--   • subscriptions_insert_instructor — проверяла только «sold_by — это я», но
--     не цену и не paid_at: можно было завести себе оплаченный абонемент на
--     любую сумму и накачать им общий котёл 15%, который делится на всех;
--   • sub_adjustments_insert_staff — начислить произвольные минуты на ЛЮБОЙ
--     абонемент (комментарий обязателен, но пишет его тот же человек).
--     Приложение этой политикой не пользуется вообще: корректировки вносит
--     только админ (adjustMinutesAction), у него свои права.
--
-- Приложению эти политики нужны были ради восьми конкретных записей, и все
-- восемь живут в одном файле (src/app/[locale]/instructor/actions.ts). Все они
-- переведены на service_role-клиент, где НАБОР КОЛОНОК задаёт код:
--   заявки       — принять / отказаться (только accepted_by + accepted_at),
--                  закрыть в статус done при записи клиента и продаже
--                  абонемента (status + client_id + payment_method_id);
--   абонементы   — продажа (цена и минуты остаются default'ами базы, sold_by
--                  берётся из сессии) и два статуса: expired (срок вышел) и
--                  used_up (минуты кончились);
--   награды      — вставка награды агенту размером из agents.commission_fixed.
-- Условия .eq/.is в коде остались на месте: «принять» по-прежнему берёт только
-- свободную подтверждённую заявку, «отказаться» — только свою.
--
-- ЧИТАТЬ инструктор продолжает всё то же самое: select-политики не трогаем,
-- иначе развалятся списание минут, поиск клиента и лента записей.
--
-- Админ ничего не теряет: у него отдельные политики *_admin_all (0005), они
-- перекрывают все три таблицы целиком.
-- Механик через эти политики не ходил: заявки он только создаёт
-- (bookings_insert_mechanic, 0029), абонементов и наград не касается вовсе.

-- ── bookings ─────────────────────────────────────────────────────────────────
-- Политика покрывала инструктора и админа; админа держит bookings_admin_all,
-- поэтому строку убираем целиком, а не переписываем под одну роль.
drop policy if exists bookings_update_staff on bookings;

-- ── subscriptions ────────────────────────────────────────────────────────────
-- select-политика subscriptions_select_staff остаётся: без неё инструктор не
-- увидит остаток минут на экране списания.
drop policy if exists subscriptions_update_instructor on subscriptions;
drop policy if exists subscriptions_insert_instructor on subscriptions;

-- ── subscription_adjustments ─────────────────────────────────────────────────
-- Политика покрывала инструктора и админа; админа держит
-- sub_adjustments_admin_all (0007), а инструктор ею и не пользовался.
-- Чтение (sub_adjustments_select_staff) НЕ трогаем: без корректировок
-- инструктор посчитает неверный остаток минут при списании.
drop policy if exists sub_adjustments_insert_staff on subscription_adjustments;

-- ── referral_rewards ─────────────────────────────────────────────────────────
drop policy if exists rewards_insert_instructor on referral_rewards;

