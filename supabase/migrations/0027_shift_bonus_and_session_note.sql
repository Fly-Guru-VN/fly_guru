-- 0027: премия за выход и примечание к сессии.
-- Накатывается вручную через Supabase SQL Editor (как 0001–0026).
--
-- Пачка правок №9, паки 2 и 3.
--
-- Премия за выход (300 000 ₫) теперь начисляется только за смену, отработанную
-- по регламенту: закрыта, открыта до 9:00, закрыта после 18:00. Но регламент
-- живой — шторм, поломка, подмена; последнее слово за админом. Поэтому две
-- колонки: bonus_cancelled («премию снять») и bonus_comment («за что»).
-- Причина хранится рядом с флагом, а не в общей заметке смены: через месяц при
-- разборе выплат «почему у него на 300к меньше» — единственный внятный ответ.
--
-- Отдельно от note: note — это план админа на смену («работает с Петей»),
-- bonus_comment — постфактум-решение по деньгам.
alter table shifts
  add column if not exists bonus_cancelled boolean not null default false,
  add column if not exists bonus_comment text;

-- Примечание к записи клиента со стороны инструктора — то же самое, что
-- «Комментарий» в админской форме сессии, которого у инструктора не было.
alter table sessions
  add column if not exists note text;
