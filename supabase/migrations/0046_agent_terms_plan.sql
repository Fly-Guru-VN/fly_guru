-- 0046: персональные условия агента («тариф»).
-- Накатывается вручную через Supabase SQL Editor (как 0001–0045).
--
-- ── Зачем ────────────────────────────────────────────────────────────────────
-- С 16.08.2026 условия агентской ссылки одни на всех и лежат в коде
-- (src/lib/agentTerms.ts): гостю −100 000 ₫ за базовое и −200 000 ₫ за парное,
-- агенту 200 000 ₫ и 300 000 ₫. Начальник договорился с одним партнёром на
-- других условиях: агенту 20% с чека, гостю −5% — и только на этих же двух
-- услугах. Класть эти проценты «на всех» нельзя: у остальных агентов условия
-- прежние.
--
-- Поэтому у агента появляется ТАРИФ — имя набора условий. Сами числа остаются
-- в коде (один файл, под тестами), в базе хранится только выбор:
--
--   'standard' — как было: фикс 100к/200к гостю, 200к/300к агенту
--   'pct-20'   — гостю −5%, агенту 20% с чека (после скидки)
--
-- Новый тариф в будущем = строчка в agentTerms.ts + значение в check ниже.
--
-- ⚠️ НАКАТЫВАТЬ ДО ДЕПЛОЯ. Код после этой правки читает agents.terms_plan без
-- страховки «а вдруг колонки ещё нет» (страховки такого рода из проекта
-- убираются, см. lib/auth.ts и lib/bookingClaim.ts). Если выкатить код раньше
-- миграции, запросы по агентской ссылке начнут падать: скидка и награда
-- перестанут применяться до наката.

-- Тариф. Значение по умолчанию — 'standard': все существующие агенты остаются
-- ровно на тех условиях, на которых работали.
alter table agents
  add column if not exists terms_plan text not null default 'standard';

-- Опечатка в тарифе = молча неправильные деньги (неизвестное имя откатилось бы
-- к стандартным условиям, и агент недополучил бы свои проценты). Поэтому
-- список значений стережёт база, а не только код.
alter table agents drop constraint if exists agents_terms_plan_check;
alter table agents
  add constraint agents_terms_plan_check
  check (terms_plan in ('standard', 'pct-20'));

comment on column agents.terms_plan is
  'Тариф агента: standard (фикс) | pct-20 (гостю −5%, агенту 20% с чека). Числа — в src/lib/agentTerms.ts';

