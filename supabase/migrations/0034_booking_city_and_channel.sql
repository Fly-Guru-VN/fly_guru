-- 0034: город и канал записи
--
-- Зачем: в заявке не было города вовсе (он жил только в карточке клиента и
-- заполнялся по желанию), а «откуда пришёл» ограничивался пятью вариантами из
-- кода — вписать «пляж Bãi Dài» или «отель Ariyana» было некуда. Теперь оба
-- поля спрашиваются обязательно: и в «Новой заявке», и в «Записать клиента».
--
-- bookings.city — город гостя из заявки. Текст, а не справочник: люди приезжают
-- откуда угодно, список пришлось бы дополнять каждый день. Nullable — у старых
-- заявок и у заявок с сайта (гость город не указывает) поля просто нет,
-- задним числом ничего не проставляем.
alter table bookings add column if not exists city text;

-- sessions.channel — как человек записался на ЭТО занятие: ключ из списка
-- (beach/call/whatsapp/…) или произвольный текст, если канал вписали руками.
-- Та же колонка по смыслу, что bookings.src, только у занятия: запись через
-- «Записать клиента» заявку не создаёт, и канал терялся.
alter table sessions add column if not exists channel text;

comment on column bookings.city is 'Город гостя, свободный текст. Обязателен в формах CRM, у заявок с сайта пуст.';
comment on column sessions.channel is 'Канал записи: ключ из MANUAL_CHANNELS (lib/channels.ts) или свободный текст.';
