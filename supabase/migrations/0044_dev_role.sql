-- 0044: новая роль — разработчик (dev).
-- Накатывается вручную через Supabase SQL Editor (как 0001–0043).
--
-- Кто это. David: делает саму систему, ведёт школу вместе с админом и получает
-- за это зарплату (фикс за неделю плюс свой 1% с оборота). До сих пор он
-- работал под общим админским аккаунтом школы, и его выплаты приходилось
-- вносить руками — своей строки в расчёте у него не было.
--
-- Права. dev = админ, БЕЗ ИСКЛЮЧЕНИЙ: те же разделы, тот же кабинет /admin.
-- Отличий ровно два, и оба не про доступ: у него свой аккаунт (видно, кто что
-- сделал) и ему начисляется ЗП. Как именно dev получает админские права в RLS —
-- см. следующий файл, 0045.
--
-- ВАЖНО: этот файл накатывается ОТДЕЛЬНО и ПЕРВЫМ, до 0045. Postgres не
-- разрешает использовать только что добавленное значение enum в той же
-- транзакции («unsafe use of new value of enum type»), а SQL Editor выполняет
-- весь скрипт одной транзакцией. Ровно та же пара, что 0039 + 0040 у СММщика
-- и 0028 + 0029 у механика.

alter type user_role add value if not exists 'dev';
