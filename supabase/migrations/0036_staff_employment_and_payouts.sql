-- 0036: приём и увольнение инструктора, оплата в заявке, отметка «ЗП выдана».
-- Накатывается вручную через Supabase SQL Editor (как 0001–0035).
--
-- Пачка правок №25 (prompts/prompt 10.txt), пункты 1, 4, 5.
--
-- ── Зачем ────────────────────────────────────────────────────────────────────
-- Живой случай: в школе работали четверо, пятого числа одного уволили. Начальник
-- выплатил ему ЗП за отработанную неделю и хочет убрать человека из системы —
-- но так, чтобы в базе осталось, что такой инструктор был и сколько ему отдали.
--
-- Раньше «убрать» можно было только удалением строки users: сессии теряли
-- инструктора (on delete set null), а прошлые расчёты ЗП становились
-- непересчитываемыми. Поэтому увольнение — это дата, а не delete.

-- ── users: трудовой период ───────────────────────────────────────────────────
-- Обе даты — рабочие дни ВКЛЮЧИТЕЛЬНО:
--   hired_at = первый рабочий день (пусто = «работал всегда», так у всех, кто
--              заведён до этой миграции);
--   left_at  = ПОСЛЕДНИЙ рабочий день (пусто = работает сейчас).
-- Человек «в штате на дату D», если (hired_at is null or hired_at <= D)
--                                и (left_at  is null or D <= left_at).
--
-- От этого зависит дележ котла абонементов: 15% с каждого абонемента делятся
-- между теми, кто был в штате В ДЕНЬ ЕГО ОПЛАТЫ. Уволенный пятого числа не
-- участвует в абонементах, оплаченных шестого, а принятый в середине месяца
-- получает долю с первого своего дня — без ручных пересчётов.
--
-- Что НЕ зависит от этих дат: 200 000 ₫ за выход и 15% с занятий дня. Они и так
-- привязаны к фактическим сменам и сессиям, а уволенный их больше не заводит.
alter table users add column if not exists hired_at date;
alter table users add column if not exists left_at  date;

comment on column users.hired_at is 'Первый рабочий день (включительно). NULL = работал с самого начала.';
comment on column users.left_at  is 'Последний рабочий день (включительно). NULL = работает сейчас.';

-- ── bookings: деньги уже получены ────────────────────────────────────────────
-- Клиент написал в инстаграм и сразу оплатил, а катается послезавтра. Раньше
-- это было некуда записать: способ оплаты в заявке есть (0016), но по нему не
-- отличить «заплатит наличными на пляже» от «уже перевёл». Инструктор на пляже
-- заново спрашивал деньги.
--
-- Флаг — это ПОМЕТКА для людей, а не выручка: в отчёты деньги по-прежнему
-- попадают в момент записи занятия (sessions.amount), иначе один платёж
-- посчитался бы дважды.
alter table bookings add column if not exists paid boolean not null default false;

comment on column bookings.paid is 'Клиент уже заплатил до занятия. Пометка для инструктора; выручка считается по сессии.';

-- ── salary_payouts: «ЗП за неделю выдана» ────────────────────────────────────
-- «Расходы» показывают начисленную ЗП, а на руки её отдают раз в неделю и не
-- всегда всем сразу (кто-то в отъезде). Отметка отвечает на вопрос «кому я уже
-- отдал»; на чистую прибыль она не влияет — прибыль считается от начисленного.
--
-- Период хранится обеими границами включительно, как его выбрали на «Расчёте
-- выплат»: сумма зафиксирована на момент отметки (amount), поэтому поздняя
-- правка сессии не перепишет историю выплаты задним числом.
create table if not exists salary_payouts (
  id            uuid primary key default gen_random_uuid(),
  instructor_id uuid not null references users(id) on delete cascade,
  period_from   date not null,
  period_to     date not null,          -- последний день периода, включительно
  amount        bigint not null,        -- сколько отдали, ₫ (снимок расчёта)
  paid_at       timestamptz not null default now(),
  created_by    uuid references users(id) on delete set null,
  unique (instructor_id, period_from, period_to)
);

create index if not exists salary_payouts_period_idx
  on salary_payouts (period_from, period_to);

comment on table salary_payouts is 'Отметки «ЗП за период выдана». Снимок суммы на момент отметки.';

-- RLS: писать и читать может только админ — это его личная бухгалтерия.
-- Инструктору отметка не показывается вовсе: деньги ему отдают из рук в руки,
-- а спорить с галочкой в интерфейсе он не должен.
alter table salary_payouts enable row level security;

drop policy if exists salary_payouts_admin_all on salary_payouts;
create policy salary_payouts_admin_all on salary_payouts
  for all using (app_role() = 'admin') with check (app_role() = 'admin');
