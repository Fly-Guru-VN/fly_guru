begin;

-- Инструктор без доли котла абонементов (решение David от 20.10.2026).
--
-- Руслана вернули в штат на других условиях: 200 000 ₫ за выход и 15% с
-- занятий дня, когда он сам открыл смену, — а 15% с абонементов ему больше не
-- идут. Это ДАТА, а не галочка: с какого дня действуют новые условия. Флаг без
-- даты пересчитал бы задним числом уже выплаченные недели — его прошлая доля
-- ушла бы остальным. Так же устроены увольнение (left_at) и больничный (0069).
--
--   no_subs_share_from — с этого дня (включительно) абонементы делятся без
--   него; пусто = обычные условия.
--
-- Читают все сотрудники, как и hired_at/left_at: котёл считается в кабинете
-- самого инструктора, и без чужой даты его доля вышла бы неверной. Пишет только
-- сервер (service_role) в админском действии.
alter table public.users
  add column if not exists no_subs_share_from date;

comment on column public.users.no_subs_share_from is
  'С этого дня (включительно) сотрудник не получает долю котла абонементов. NULL = получает.';

commit;
