-- 0039: новая роль — СММщик.
-- Накатывается вручную через Supabase SQL Editor (как 0001–0038).
--
-- СММщик ведёт рекламу школы и работает с потоком заявок: смотрит, откуда
-- приходят люди, заводит и подтверждает записи, оформляет клиентов, ведёт
-- агентов. По деньгам ему видна выручка и воронка, но НЕ чистая прибыль,
-- ЗП инструкторов и доли учредителей — его «Статистика» собирается отдельно.
--
-- В расчёты ЗП он не попадает (там фильтр role = 'instructor'), смен не
-- открывает, инвентарь и услуги не трогает.
--
-- ВАЖНО: этот файл накатывается ОТДЕЛЬНО и ПЕРВЫМ, до 0040. Postgres не
-- разрешает использовать только что добавленное значение enum в той же
-- транзакции («unsafe use of new value of enum type»), а SQL Editor выполняет
-- весь скрипт одной транзакцией. Политики, где встречается 'smm', живут
-- в 0040 — ровно та же пара, что 0028 + 0029 у механика.

alter type user_role add value if not exists 'smm';
