-- 0042 — дата оплаты у заявки и у занятия (пачка №26, п.1).
-- Накатывается вручную через Supabase SQL Editor (как 0001–0041).
--
-- Зачем: деньги и катание случаются в разные дни. Гость написал в директ и
-- перевёл всю сумму 12 июля, а катается 12 августа. До сих пор такой чек
-- целиком ложился в август — в месяц ЗАНЯТИЯ, потому что другой даты у сессии
-- просто не было. В июльской кассе его не хватало, в августовской он был
-- лишним, и свести месяц с реальными деньгами было нельзя.
--
-- Стало: paid_on — день, когда деньги реально пришли. Не заполнен (и так у
-- всех старых строк) — значит платили в день занятия, как и раньше.
--
-- money_date — «денежная дата» строки, coalesce(paid_on, date). Вычисляется
-- базой, поэтому разойтись с paid_on не может, и по ней можно фильтровать и
-- строить индекс (обычным выражением в PostgREST фильтровать нельзя).
--
-- ЧТО СЧИТАЕТСЯ ПО НЕЙ (решение David от 12.08.2026): выручка, 35% Marina,
-- 2% CRM и чистая прибыль — то есть деньги школы.
-- ЧТО ОСТАЁТСЯ ПО ДАТЕ ЗАНЯТИЯ: ЗП инструкторов (15%, выходы, котёл
-- абонементов) и комиссии агентов — это плата за работу, а работа была в день
-- занятия; недельные выплаты пересчитывать задним числом нельзя.
-- ============================================================================

-- ── Заявка ──────────────────────────────────────────────────────────────────
-- Рядом с галочкой paid (0036): она отвечает «деньги уже получены», эта
-- колонка — «когда». Дату переносит в занятие форма записи, когда заявку
-- закрывают проведённым занятием.
alter table bookings add column if not exists paid_on date;

comment on column bookings.paid_on is
  'День, когда гость заплатил (если не в день занятия). Едет в sessions.paid_on при закрытии заявки.';

-- ── Занятие ─────────────────────────────────────────────────────────────────
alter table sessions add column if not exists paid_on date;

comment on column sessions.paid_on is
  'День, когда пришли деньги за занятие. Пусто = в день занятия.';

alter table sessions
  add column if not exists money_date date
  generated always as (coalesce(paid_on, date)) stored;

comment on column sessions.money_date is
  'Денежная дата занятия = coalesce(paid_on, date). По ней считаются выручка, 35% Marina, 2% CRM и прибыль; ЗП инструкторов — по date.';

-- Отчёты всегда просят диапазон денежных дат — без индекса это seq scan по
-- всей таблице на каждый заход в «Статистику».
create index if not exists sessions_money_date_idx on sessions (money_date);
