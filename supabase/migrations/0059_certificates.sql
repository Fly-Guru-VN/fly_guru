-- ============================================================================
-- 0059 — подарочные сертификаты.
-- Накатывается вручную через Supabase SQL Editor (как 0001–0058), ПЕРЕД пушем
-- кода: без таблицы вкладка «Сертификаты» и проверка номера в форме записи
-- упадут на первом же запросе — фолбэков в коде нет (правило с 16.08.2026).
--
-- ── Зачем ────────────────────────────────────────────────────────────────────
-- Решение David от 08.09.2026: школа продаёт сертификаты на бумаге. Админ
-- заводит номер в CRM (имя, телефон, услуга), номер пишется на бланке от руки.
-- Гость вводит его в форме записи — услуга подставляется сама, заявка дальше
-- идёт как обычная.
--
-- Правила начальника: сертификат действует ТРИ МЕСЯЦА со дня создания и
-- сгорает при использовании. Отсюда expires_at с дефолтом и used_at.
--
-- ── Почему таблица закрыта наглухо ───────────────────────────────────────────
-- RLS включена, политик нет ни одной — значит, ни один клиентский ключ (ни
-- анонимный с сайта, ни JWT сотрудника) не прочитает и не изменит здесь
-- ничего. Вся работа идёт через сервер служебным ключом после проверки роли,
-- как договорились в 0055: RLS не умеет ограничивать НАБОР колонок, а тут
-- цена ошибки — «сертификат погасился сам» или «номера подобрали перебором».
--
-- Наружу, в форму записи, сервер отдаёт ровно одно название услуги — ни имени
-- владельца, ни телефона, ни срока (см. api/certificates/check).
-- ============================================================================

begin;

create table if not exists public.certificates (
  -- Номер хранится нормализованным: только заглавные буквы и цифры, без
  -- дефисов и пробелов. На бланке его пишут как «FG-7K3M-92QD», а гость
  -- вводит как придётся — сравнивать надо одно и то же.
  id              uuid primary key default gen_random_uuid(),
  code            text not null,
  client_name     text not null,
  phone           text not null,
  service_id      uuid not null references services(id) on delete restrict,
  issued_at       timestamptz not null default now(),
  -- Три месяца со дня создания. Дефолт в базе, а не в коде: срок — правило
  -- школы, и он должен быть один для всех дверей, откуда заводят сертификат.
  expires_at      timestamptz not null default now() + interval '3 months',
  -- Погашен: проставляется в момент, когда номер ушёл в заявку. Пара
  -- «used_at is null» + условие срока — это и есть замок от повторного
  -- использования: два одновременных нажатия увидят строку по очереди, и
  -- второе не найдёт её подходящей.
  used_at         timestamptz,
  used_booking_id uuid references bookings(id) on delete set null,
  created_by      uuid references users(id) on delete set null,
  note            text
);

-- Один номер — один сертификат. Индекс же служит и поиском при проверке.
create unique index if not exists certificates_code_uidx on public.certificates (code);
-- Лента во вкладке отсортирована по дате выдачи.
create index if not exists certificates_issued_idx on public.certificates (issued_at desc);

alter table public.certificates enable row level security;

commit;
