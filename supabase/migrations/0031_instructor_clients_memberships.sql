-- 0031: последние две прямые записи инструктора в базу.
-- Накатывается вручную через Supabase SQL Editor, ПОСЛЕ 0030.
--
-- Продолжение 0030, тот же принцип: RLS проверяет строку, но не набор колонок,
-- поэтому «роль = instructor» в with check означает «пиши в этой таблице что
-- хочешь». После 0030 у инструктора оставались две такие двери.
--
-- 1. clients_insert_instructor (0005). Инструктор заводил карточки клиентов
--    напрямую. Само по себе не страшно (подделанная карточка стоит ноль), но
--    рядом обнаружилось кое-что похуже: политики UPDATE на clients у него нет
--    и никогда не было, а код в findOrCreateClient дописывал существующему
--    клиенту ник в Telegram именно апдейтом. RLS этот апдейт молча отбрасывал:
--    ноль изменённых строк — это не ошибка, и никто ничего не замечал. Ник
--    просто не сохранялся. Теперь и вставка, и дописывание ника идут
--    service_role-клиентом — заодно чинится и это.
--
-- 2. memberships_insert_instructor (0005). Осталась со времён, когда продажа
--    абонемента автоматически делала клиента членом клуба. Клуб не запущен,
--    обе продажи членство НЕ создают (см. комментарии в коде), членов заводит
--    админ руками на вкладке «Члены клуба». Приложение этой политикой не
--    пользуется вообще — чистая поверхность атаки.
--
-- ЧИТАТЬ инструктор продолжает и клиентов (clients_select_staff — иначе не
-- найти человека по телефону), и членства (memberships_select_staff).
-- Админ не затронут: clients_admin_all и memberships_admin_all перекрывают обе
-- таблицы целиком. Механик клиентов не создаёт — он заводит заявку.

drop policy if exists clients_insert_instructor on clients;
drop policy if exists memberships_insert_instructor on memberships;

