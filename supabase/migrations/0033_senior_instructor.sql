-- 0033: старший инструктор — кто открывает смену по-настоящему.
-- Накатывается вручную через Supabase SQL Editor (как 0001–0032).
--
-- Пачка правок №11 (prompts 7), п.1.
--
-- Живой сценарий: на пляже работают двое. Доску и крыло осматривает и
-- фотографирует один — старший; второму снимать то же самое второй раз
-- бессмысленно, ему нужно только подтвердить, что он пришёл вовремя. Раньше
-- система требовала полный комплект снимков от обоих, и второй либо снимал
-- дубли, либо не открывал смену вовсе — а без opened_at ему не идут 300 000 ₫
-- за выход.
--
-- Поэтому:
--   • users.senior — кто на смене старший. Ставит админ в Настройках;
--     на роль механика не влияет (регламент 9:00/18:00 к нему и так не
--     применяется, а оборудование он снимает по своей работе).
--   • shift_photos.kind получает значение 'checkin' — тот самый одиночный
--     кадр «я на пляже». Отдельным видом, а не 'extra': по нему видно, что
--     человек отметился, а не снял дефект.
--
-- Начисление ЗП не меняется: отметка о приходе пишет те же opened_at/closed_at,
-- поэтому регламент «открыл до 9:00, закрыл после 18:00» работает для обоих.

alter table users
  add column if not exists senior boolean not null default false;

-- Констрейнт создавался вместе с таблицей (0019), имя автоматическое.
alter table shift_photos drop constraint if exists shift_photos_kind_check;
alter table shift_photos
  add constraint shift_photos_kind_check
  check (kind in ('board', 'wing', 'comms', 'extra', 'checkin'));
