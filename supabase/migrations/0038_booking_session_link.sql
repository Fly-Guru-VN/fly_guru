-- ============================================================================
-- 0038 — чем именно закрыта заявка: занятием или абонементом
--
-- Зачем. Заявка и занятие до сих пор жили порознь. «Записать клиента» помечало
-- заявку выполненной и отдельно писало сессию, но связи между ними в базе не
-- оставалось: по строке в «Сессиях» нельзя сказать, из какой она заявки, а по
-- заявке — состоялось ли занятие вообще. Живой случай (заявки 75/76 от
-- 11.08.2026): мама записала себя и дочку на обучение, инструктор оформил ОДНО
-- парное занятие за 3,5 млн по заявке 75, а заявку 76 закрыл кнопкой
-- «Отменить». В базе дочка теперь числится отказом, хотя каталась, и в воронке
-- «Источников» это выглядит как потерянный клиент.
--
-- Почему ссылка живёт на ЗАЯВКЕ, а не на сессии. Занятие бывает одно на
-- несколько заявок — то самое парное обучение (и любой семейный заход). Если
-- бы booking_id стоял на сессии, одна сессия смогла бы закрыть ровно одну
-- заявку, и вторую опять пришлось бы отменять. Здесь же обе заявки указывают
-- на одну сессию: 75 → занятие, 76 → то же занятие. Деньги при этом
-- считаются по сессиям и удвоиться не могут.
--
-- subscription_id — та же мысль для заявок на абонемент: они закрываются не
-- занятием, а продажей. Без этой колонки любая проданная заявка выглядела бы
-- как «выполнена, но занятия нет».
--
-- on delete set null: удалённая сессия не должна уносить с собой заявку —
-- заявка просто снова становится «закрытой без занятия», и это видно в ленте.
-- ============================================================================

alter table bookings add column if not exists session_id      uuid references sessions(id)      on delete set null;
alter table bookings add column if not exists subscription_id uuid references subscriptions(id) on delete set null;

comment on column bookings.session_id is
  'Занятие, которым закрыта заявка. Одна сессия может закрывать несколько заявок (парное обучение).';
comment on column bookings.subscription_id is
  'Абонемент, продажей которого закрыта заявка. Заполняется вместо session_id.';

-- Ищем в обе стороны: «какие заявки закрыты этим занятием» (карточка сессии)
-- и «есть ли занятие у этой заявки» (лента заявок).
create index if not exists bookings_session_idx      on bookings (session_id)      where session_id      is not null;
create index if not exists bookings_subscription_idx on bookings (subscription_id) where subscription_id is not null;

