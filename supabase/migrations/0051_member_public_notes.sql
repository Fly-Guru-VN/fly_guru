-- ============================================================================
-- 0051: отдельные заметки, которые разрешено показывать клиенту.
--
-- bookings.internal_note и sessions.note изначально создавались как рабочие
-- поля сотрудников. Клиентский Mini App ошибочно читал их напрямую и мог
-- показать гостю внутреннюю договорённость, замечание или служебный контекст.
--
-- Новые поля имеют явный контракт: содержимое public_note можно вернуть
-- владельцу карточки клиента. Старые заметки намеренно не копируем — по тексту
-- нельзя надёжно отличить слова гостя от дописанного сотрудником комментария.
-- ============================================================================

alter table bookings
  add column if not exists public_note text;

alter table sessions
  add column if not exists public_note text;

comment on column bookings.public_note is
  'Заметка, которую безопасно показывать связанному клиенту в Mini App';

comment on column sessions.public_note is
  'Заметка, которую безопасно показывать связанному клиенту в Mini App';
