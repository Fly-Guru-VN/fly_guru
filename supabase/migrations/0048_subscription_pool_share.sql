-- ============================================================================
-- 0048 — абонемент админа можно отправить в общий котёл.
-- Накатывается вручную через Supabase SQL Editor (как 0001–0047), ПЕРЕД пушем
-- кода: без колонки экраны абонементов упадут на select.
--
-- ── Зачем ────────────────────────────────────────────────────────────────────
-- Правило до сегодня было простое: 15% с абонемента идут в общий котёл
-- инструкторов, только если абонемент продал полевой состав (инструктор или
-- СММщик). Продажа админа — прибыль школы, мимо котла: он босс, ему платят
-- не по формуле (src/lib/salary → getSubsShares).
--
-- Решение David от 21.08.2026: бывает наоборот. Денис (админ) продал два
-- абонемента и хочет, чтобы эти 15% ушли ребятам — фактически продажу сделала
-- школа, а катать клиента будут они. Раньше такое можно было провести только
-- враньём в поле «Продал»: записать продажу на инструктора, и тогда она
-- испортила бы ему справку «сам продал N штук».
--
-- ── Что здесь ────────────────────────────────────────────────────────────────
-- Одна колонка-флаг. По умолчанию false — все старые абонементы и все будущие
-- продажи ведут себя ровно как раньше, пока флаг не поставят руками.
--
-- Полевого состава флаг не касается: у инструктора и СММщика 15% уходят в
-- котёл всегда, по факту продажи.
--
-- Отдельных политик не нужно: колонка живёт в subscriptions, а её правят
-- админ своим ключом (policy *_admin_all) и СММщик служебным (0040).
-- ============================================================================

alter table subscriptions
  add column if not exists pool_share boolean not null default false;

comment on column subscriptions.pool_share is
  'Продажа не полевого сотрудника (админ/dev/механик), которую всё равно делят '
  'в общий котёл 15% между сменщиками дня оплаты. У инструктора и СММщика '
  'котёл считается независимо от этого флага.';
