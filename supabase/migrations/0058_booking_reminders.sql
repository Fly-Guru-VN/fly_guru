-- ============================================================================
-- 0058 — напоминания клиенту о его записи.
-- Накатывается вручную через Supabase SQL Editor (как 0001–0057), ПЕРЕД пушем
-- кода: крон /api/cron/booking-reminder пишет в эти колонки, и без них он
-- упадёт на каждом запуске.
--
-- ── Зачем ────────────────────────────────────────────────────────────────────
-- Решение David от 08.09.2026: клиент, записавшийся из кабинета, получает два
-- напоминания в бота — вечером накануне (в 20:00, когда закрывается запись на
-- завтра) и за два часа до занятия, чтобы успеть отменить самому: отмена
-- закрывается за час до начала.
--
-- ── Почему две колонки, а не одна ────────────────────────────────────────────
-- Напоминаний два, и по одной отметке нельзя понять, какое уже ушло. Отдельные
-- колонки заодно делают крон повторяемым: перезапуск (а Vercel умеет позвать
-- тот же путь дважды) не пришлёт человеку второе такое же сообщение.
-- ============================================================================

begin;

alter table public.bookings
  add column if not exists reminded_eve_at  timestamptz,
  add column if not exists reminded_soon_at timestamptz;

-- Крон «за два часа» бегает каждые полчаса и каждый раз спрашивает заявки
-- одного дня. Индекс по дате с отсечкой живых статусов держит этот запрос
-- маленьким независимо от того, сколько заявок накопилось в архиве.
create index if not exists bookings_reminder_idx
  on public.bookings (preferred_date)
  where status in ('new', 'contacted', 'confirmed');

commit;
