-- ============================================================================
-- 0060 — язык, на котором гость оставил заявку.
-- Накатывается вручную через Supabase SQL Editor (как 0001–0059), ПЕРЕД пушем
-- кода: форма записи начнёт присылать это поле сразу после выкатки.
--
-- ── Зачем ────────────────────────────────────────────────────────────────────
-- С 09.09.2026 сайт говорит на семи языках, и заявки пошли не только от
-- русскоязычных. Без этой колонки админ видит заявку от корейца ровно так же,
-- как от соотечественника, и звонит ему по-русски — разговор заканчивается,
-- не начавшись. Колонка отвечает на один вопрос: на каком языке человек читал
-- сайт, когда записывался.
--
-- ── Почему text, а не enum ───────────────────────────────────────────────────
-- Список языков живёт в коде (src/i18n/locales.ts) и будет меняться. Enum
-- пришлось бы менять миграцией на каждый новый язык, а рассинхрон enum'а с
-- деплоем этот проект уже проходил на роли механика. Значение проверяет
-- сервер: в базу попадает только код из списка, всё остальное — NULL.
--
-- NULL — это «неизвестно»: все заявки до этой миграции, заявки из кабинета
-- агента и из кабинета клиента. Отдельного «ru» им не проставляем: догадка
-- задним числом хуже честного пробела.
-- ============================================================================

begin;

alter table public.bookings
  add column if not exists locale text;

comment on column public.bookings.locale is
  'Язык сайта, на котором гость оставил заявку (ru/en/vi/ko/zh/es/de). NULL — неизвестно.';

commit;
