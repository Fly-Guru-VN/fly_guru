"use client";

import { usePathname } from "next/navigation";

// Мягкое появление страницы при переходе: нажал «Обучение» — содержимое не
// подменяется рывком, а всплывает.
//
// Как это работает: обёртка помечена key={pathname}. Меняется адрес — React
// размонтирует старое поддерево и смонтирует новое, а CSS-анимация на свежем
// узле проигрывается заново. Готовый next/template сюда не подошёл: он
// перемонтируется и при смене только параметров адреса, а у нас ими открывается
// карточка дня в календаре (?d=…) — календарь мигал бы на каждый тап по дню.
// Поэтому ключ именно pathname, без search-параметров.
//
// Шапка и подвал остаются снаружи — двигается только содержимое страницы,
// иначе интерфейс «прыгал» бы целиком.
export function PageTransition({ children }: { children: React.ReactNode }) {
  const pathname = usePathname();
  return (
    <div key={pathname} className="animate-page-in">
      {children}
    </div>
  );
}
