"use client";

import { useState } from "react";

// «Куда человек нажал», пока страница ещё не открылась.
//
// Зачем: плашка активного раздела (SlidingHighlight) стоит там, куда её ставит
// usePathname, а он в App Router меняется ТОЛЬКО после того, как новая страница
// собралась. Между нажатием и этим моментом плашка честно показывает старый
// раздел — на телефоне это читается как «моргнула старой вкладкой и лишь потом
// переключилась» (David, 04.09.2026).
//
// Поэтому адрес для подсветки берём отсюда: сразу после нажатия это цель, а
// когда переход случился — снова настоящий адрес. Сама навигация не меняется,
// это только про то, что видно.
export function useOptimisticPath(pathname: string) {
  const [target, setTarget] = useState<string | null>(null);
  // Адрес, при котором цель ставили. Сравнение с ним — единственный способ
  // понять, что переход состоялся, не заводя эффекта: эффект здесь означал бы
  // лишний кадр со старой подсветкой, ровно то, от чего уходим.
  const [setAt, setSetAt] = useState(pathname);

  if (setAt !== pathname) {
    // Адрес сменился — цель отработала. Правка состояния прямо в рендере, как
    // это описано у React для «сбросить состояние при смене входных данных»:
    // React перерисует компонент заново до того, как что-то попадёт на экран.
    setSetAt(pathname);
    setTarget(null);
  }

  return {
    path: target ?? pathname,
    goTo: (href: string) => {
      setSetAt(pathname);
      setTarget(href);
    },
  };
}
