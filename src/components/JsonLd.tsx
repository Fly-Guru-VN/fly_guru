// Вставка разметки schema.org на страницу.
//
// Разметка живёт в теге <script type="application/ld+json"> — человек её не
// видит, читают только поисковики.
//
// Про «<» в тексте: если в данных попадётся строка вроде «<b>», браузер решит,
// что тег script здесь и кончился, и остаток разметки вывалится на страницу
// текстом. Поэтому «<» заменяем на его безопасную запись — для JSON это тот же
// самый символ, а браузер уже не путается.
//
// Внутрь попадают только НАШИ данные: константы из lib/schema.ts, тексты из
// content/services.ts и числа-цены из базы. Ничего, что вводит посетитель,
// сюда не приходит — иначе одной замены «<» было бы мало.
export function JsonLd({ data }: { data: object }) {
  return (
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{
        __html: JSON.stringify(data).replace(/</g, "\\u003c"),
      }}
    />
  );
}
