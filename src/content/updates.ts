// говорит, стоит ли читать дальше: админу не нужны подробности про кнопку,
// которой у него нет, но знать, что она у инструктора появилась, полезно.
export type UpdateWhere = "instructor" | "admin" | "both";

export const UPDATE_WHERE_LABEL: Record<UpdateWhere, string> = {
  instructor: "кабинет инструктора",
  admin: "кабинет админа",
  both: "оба кабинета",
};

export interface UpdateEntry {
  date: string; // YYYY-MM-DD
  kind: UpdateKind;
  where: UpdateWhere;
  title: string;
  text: string;
  // Метка «⚠️ важно»: карточка становится заметной и внутри своего дня встаёт
  // первой. Ставим, только если правку реально нельзя пропустить:
  //   • изменились деньги — ЗП, цены, награда агента, списание минут;
  //   • изменился порядок работы — что-то теперь делается по-другому;
  //   • пропала или переехала кнопка, которой пользовались каждый день;
  //   • нужно что-то проверить руками (например, свои записи за прошлый месяц).
  // Если помечать всё подряд, метка перестанет работать: три «важно» подряд
  // человек уже листает не читая.
  important?: boolean;
}

