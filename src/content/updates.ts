// Лента изменений — то, что видно на вкладке «Обновления» в кабинете
// инструктора и в кабинете админа.
//
// Зачем: новые функции появлялись молча, а старые так же молча исчезали
// (форму «Поправить минуты», например, убрали намеренно — но снаружи это
// выглядело как поломка). Здесь коротко и человеческим языком: что нового,
// что починили, что убрали и почему.
//
// КАК ДОПОЛНЯТЬ: добавить запись в начало массива (свежее — сверху) в конце
// работы над пачкой правок. Никаких миграций: текст едет вместе с самой
// правкой, так что лента не может опередить функцию или отстать от неё.
//
// Правила текста:
//   • title — как сказал бы человек, а не как называется коммит;
//   • text — 1–3 предложения: что изменилось и где это в кабинете;
//   • where — чей это кабинет; без поля запись считается общей;
//   • important — только для правок, мимо которых пройти нельзя (см. ниже);
//   • без английских терминов, без имён файлов и колонок в базе.

