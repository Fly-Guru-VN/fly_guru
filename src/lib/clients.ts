import type { createClient } from "@/lib/supabase/server";
import type { createAdminClient } from "@/lib/supabase/admin";

// Загрузка карточек клиентов целиком, без тихого потолка (ревизия 2026-07-25).
//
// Зачем это вообще. Клиента у нас ищут по телефону в памяти, а не запросом:
// номера в заявках лежат «как ввёл гость» (+84, пробелы, дефисы), поэтому
// сравнивает их phonesMatch по последним 9 цифрам. Значит списку клиентов надо
// приехать на сервер целиком.
//
// Что было не так. Везде стояло .limit(1000) — «клиентов сотни, не миллионы».
// Пока их пять, это правда. Но на 1001-м клиенте PostgREST молча отдал бы
// первую тысячу, и дальше всё ломается ТИХО: дедуп перестанет находить
// существующего человека и заведёт ему вторую карточку, проверка «первый раз у
// нас?» ответит «первый», а в выпадающих списках клиент просто исчезнет. Ни
// ошибки, ни строчки в логе — а история клиента расползётся по двум карточкам.
//
// Как сейчас. Читаем страницами по 1000, пока страницы полные. Сегодня это
// один запрос, на трёх тысячах клиентов — три. Порядок задаём по id: без
// order у range нет гарантии, что страницы не перекроются и не потеряют строки.
//
// Когда это перестанет годиться: если клиентов станет десяток тысяч, выпадающие
// списки надо будет переводить на поиск по подстроке на стороне базы, а
// сравнение телефонов — на отдельную колонку с нормализованным номером и
// индексом. Тогда этот модуль и станет местом, где это чинится один раз.

type Supabase =
  | Awaited<ReturnType<typeof createClient>>
  | ReturnType<typeof createAdminClient>;

const PAGE_SIZE = 1000;

export interface LoadClientsOptions {
  /** Только карточки с телефоном — тем, у кого его нет, поиск по номеру не нужен. */
  onlyWithPhone?: boolean;
}

/**
 * Все карточки клиентов с нужными колонками. Колонки передаёт вызывающий: где-то
 * нужен ник в телеге, где-то допуск к выездам, и тащить всё подряд незачем.
 *
 * Ошибку возвращаем текстом, а не кидаем: часть вызывающих (подсказки, формы)
 * умеет корректно промолчать, а часть — показать «не удалось найти клиента».
 */
export async function loadAllClients<T>(
  supabase: Supabase,
  columns: string,
  options: LoadClientsOptions = {},
): Promise<{ rows: T[]; error: string | null }> {
  const rows: T[] = [];

  for (let from = 0; ; from += PAGE_SIZE) {
    let query = supabase.from("clients").select(columns).order("id");
    if (options.onlyWithPhone) query = query.not("phone", "is", null);

    const { data, error } = await query.range(from, from + PAGE_SIZE - 1);
    if (error) return { rows, error: error.message };

    const page = (data ?? []) as unknown as T[];
    rows.push(...page);
    // Неполная страница = список кончился. Ровно кратное число клиентов даст
    // один лишний пустой запрос — это дешевле, чем гадать.
    if (page.length < PAGE_SIZE) break;
  }

  return { rows, error: null };
}
