// впервые и оплатил, получает +10 минут к обучению или к абонементу, а
// пригласивший — +20 бонусных минут на отдельный баланс. Денег нет ни у кого,
// поэтому кассу и проценты это не трогает.
//
// ЭТОТ ФАЙЛ ЧИТАЮТ И СЕРВЕР, И БРАУЗЕР: только числа и чистые функции. Всё, что
// требует базы (кто член клуба, новый ли клиент, остаток), — в lib/referrals.

/** Сколько бонусных минут получает пригласивший за одного нового клиента. */
export const REFERRER_REWARD_MINUTES = 20;

/** Сколько минут сверху получает приглашённый. */
export const FRIEND_BONUS_MINUTES = 10;

/** services.code услуги, которой тратят бонусные минуты (миграция 0063). */
export const BONUS_SERVICE_CODE = "bonus-minutes";

/**
 * Положены ли приглашённому +10 минут на эту услугу. Только обучение (любое,
 * включая парное, детское и индивидуальное) и абонемент — на тандем, прокат и
 * экскурсии бонуса нет.
 */
export function friendBonusApplies(category: string | null | undefined): boolean {
  return category === "training" || category === "subscription";
}

/** Строка в заметку занятия: инструктор видит её в истории клиента. */
export const FRIEND_BONUS_NOTE = `+${FRIEND_BONUS_MINUTES} мин по приглашению`;
