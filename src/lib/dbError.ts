// Ошибка чтения из базы там, где считаются деньги или доступный клиенту лимит.
//
// Зачем это отдельным файлом (ревизия 15.08.2026). В четырёх местах чтение
// выплат было написано так: запрос не удался — считаем, что выплат не было.
// Ошибку никто не видел, а её последствия выглядели как обычные цифры:
// «деньги на руках» больше, чем в кассе (вычитать-то нечего), «осталось
// выдать» больше на всё уже выданное. То есть школа рисковала заплатить
// второй раз, и никакого признака поломки на экране не было.
//
// Правило простое: ноль бывает только тогда, когда база честно ответила «строк
// нет». Не ответила — это ошибка, и её надо показать, а не подменять нулём.
// Да, страница при этом падает на экран ошибки — это хуже, чем работающая
// вкладка, но лучше, чем вкладка, которая уверенно врёт про деньги.
//
// Для действий (запись) такой же помощник живёт в admin/actions.ts
// (`failIfError`) — здесь он для чтения, поэтому и текст другой. Тем же
// правилом защищён остаток минут абонемента: ложный остаток способен разрешить
// списание сверх купленного лимита.

export function failIfReadError(
  error: { message: string } | string | null,
  what: string,
): void {
  if (!error) return;
  const message = typeof error === "string" ? error : error.message;
  console.error(`[read] ${what}:`, message);
  throw new Error(
    `${what}: ${message}. Цифры показывать нельзя — обновите страницу, и если повторяется, смотрите логи.`,
  );
}
