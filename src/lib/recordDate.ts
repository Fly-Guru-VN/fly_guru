// Коридор дат, в котором инструктор может записать занятие.
//
// Раньше дата жёстко приравнивалась к сегодняшнему дню: инструктор не мог ни
// внести вчерашнее занятие (забыл оформить на пляже), ни оформить клиента,
// который заплатил сегодня, а катается завтра. Каждый такой случай шёл через
// админа руками.
//
// Отсюда окно ±7 дней (пачка №10, п.2): недели хватает на «забыл вчера» и на
// «клиент записался на завтра», а промахнуться мимо месяца — а значит увезти
// занятие в чужую ЗП и чужую статистику — уже нельзя. Записи дальше по времени
// по-прежнему оформляет админ: у него дата свободная.
//
// Правило одно на форму и на экшен: в разметке min/max — подсказка (её легко
// обойти), в экшене — проверка.

import { vnShiftDays, vnToday } from "./dates";

export const RECORD_WINDOW_DAYS = 7;

export const DAY_RE = /^\d{4}-\d{2}-\d{2}$/;

// Границы для полей формы и для проверки на сервере. today передаётся явно,
// чтобы форма считала окно от той же даты, что пришла с сервера, а не от часов
// телефона (они могут врать, а у нас от даты зависят ЗП и статистика).
export function recordDateBounds(today: string = vnToday()) {
  return {
    min: vnShiftDays(today, -RECORD_WINDOW_DAYS),
    max: vnShiftDays(today, RECORD_WINDOW_DAYS),
  };
}

// Проверка даты из формы. Пустое значение — это сегодня: так экшен переживает
// и старую вкладку, открытую до появления поля.
export function checkRecordDate(
  raw: string,
): { date: string } | { error: string } {
  const today = vnToday();
  const day = raw.trim() || today;
  if (!DAY_RE.test(day)) return { error: "Дата занятия указана неверно." };

  const { min, max } = recordDateBounds(today);
  if (day < min || day > max) {
    return {
      error: `Дата занятия — не дальше ${RECORD_WINDOW_DAYS} дней от сегодня. Запись более старым или дальним числом — через админа.`,
    };
  }
  return { date: day };
}
