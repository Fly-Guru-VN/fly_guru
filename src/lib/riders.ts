// Парное катание: сколько минут уходит с абонемента, когда с него катаются
// несколько человек сразу. Отдельный модуль без зависимостей — им пользуются
// и серверные действия, и форма инструктора в браузере.
// Правило начальника (30.08.2026): если с ОДНОГО абонемента одновременно
// катаются двое по 30 минут — списывается 60. То есть с абонемента уходит
// «длительность × число катавшихся», а не длительность сессии.
//
// Отдельной колонки под число райдеров намеренно нет: в minutes_used всегда
// лежит ИТОГО списанное (60), поэтому остаток и вся статистика считаются
// старой формулой и переписывать их не пришлось. Сам факт «катались вдвоём»
// уходит в note — то самое примечание, которое уже видно в «Сессиях» у
// админа, инструктора и механика. Понадобится считать парные каталки цифрами —
// заведём колонку тогда, старые строки читаются из примечания.
export const RIDERS_MAX = 4;

// Сколько человек каталось одновременно. Пустое поле, мусор и выход за 1…4 —
// это один райдер: списать меньше положенного безопаснее, чем больше.
export function parseRiders(raw: unknown): number {
  const n = Math.trunc(Number(raw ?? 1));
  if (!Number.isFinite(n) || n < 1) return 1;
  return Math.min(n, RIDERS_MAX);
}

// Примечание к списанию: к пометке инструктора спереди приписываем, что
// катались не одни. При одном райдере примечание остаётся ровно таким, каким
// его написали, — в истории не появляется шума «1 райдер».
export function writeOffNote(riders: number, comment: string): string | null {
  const mark = riders > 1 ? `${riders} райдера одновременно` : "";
  return [mark, comment.trim()].filter(Boolean).join(" · ") || null;
}
