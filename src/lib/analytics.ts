import { track } from "@vercel/analytics";

// События сайта для аналитики Vercel.
//
// Зачем: обычная аналитика считает «человек зашёл», и на этом всё. Воронку —
// сколько из зашедших открыли форму записи и сколько реально отправили заявку —
// видно только по событиям. Их и шлём.
//
// Названия событий и меток собраны здесь одним списком: в дашборде Vercel они
// показываются как есть, и опечатка в строке даёт молчаливо потерянное
// событие, которого никто не хватится.
//
// ВАЖНО: свои события считаются только на платном тарифе Vercel (у нас Pro).
// На бесплатном вызовы просто ни к чему не приводят — сайт от этого не ломается.

export type SiteEvent =
  // Открыли форму записи (любая кнопка «Записаться» на сайте).
  | "booking_open"
  // Заявка успешно ушла на сервер. Разница между этим и booking_open и есть
  // главная цифра: сколько людей бросают форму на полпути.
  | "booking_sent"
  // Клик по контакту: телефон, мессенджер, карта, соцсеть.
  | "contact_click"
  // Переход в магазин фойлов.
  | "shop_click";

// Метка места, откуда пришло событие: шапка, первый экран, липкая кнопка внизу
// и т. д. По ней видно, какая кнопка на самом деле работает, а какая висит зря.
export type EventData = Record<string, string>;

export function trackEvent(name: SiteEvent, data?: EventData): void {
  // Блокировщики рекламы режут скрипт аналитики. Событие в этом случае просто
  // не уходит — но уронить из-за этого клик по кнопке мы не имеем права.
  try {
    track(name, data);
  } catch {
    // молча: аналитика — не то, ради чего стоит ломать страницу
  }
}
