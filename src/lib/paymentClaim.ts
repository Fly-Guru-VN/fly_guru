// Заявление об оплате абонемента (миграция 0032, пачка №10, п.5).
//
// Инструктор оформляет абонемент, деньги за который принял админ мимо CRM.
// Отметить оплату он не может — paid_at идёт в выручку месяца и в общий котёл
// 15%, а денег инструктор не видел. Поэтому он оставляет заявление: «оплату
// принял админ» или «с оплатой непонятно». Админ подтверждает его кнопкой
// «Отметить оплату» — заявление при этом снимается.

export type PaymentClaim = "admin" | "unclear";

const PAYMENT_CLAIMS: PaymentClaim[] = ["admin", "unclear"];

export function isPaymentClaim(value: string): value is PaymentClaim {
  return (PAYMENT_CLAIMS as string[]).includes(value);
}

// Короткая плашка в списках — то, что видит и инструктор, и админ.
export const PAYMENT_CLAIM_BADGE: Record<PaymentClaim, string> = {
  admin: "Оплату принял админ — подтвердить",
  unclear: "Оплата под вопросом",
};

